"""Launch posts for Canada Through Time, with every number computed from the site's data files (never typed in).

    python tools/make_launch_copy.py [--url https://...]   -> exports/launch/launch_copy.md
"""
import argparse
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "web/data"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="https://tjreeve-ship-it.github.io/canada-through-time/")
    url = ap.parse_args().url
    PA = json.loads((D / "money/public_accounts.json").read_text())
    POP = json.loads((D / "population.json").read_text())
    y = PA["years"][-1]
    tot = sum(PA["totals"][str(y)]) * 1e3
    per = tot / POP["series"]["CAN"][POP["dates"].index(f"{y - 1}-07-01")]
    C = json.loads((D / "money/contracts.json").read_text())
    ctot = sum(t for ys in C["by_proc"].values() for t, _ in ys.values())
    tn = sum(t for t, _ in C["by_proc"].get("TN", {}).values()) / ctot * 100
    ncon = sum(k for ys in C["by_proc"].values() for _, k in ys.values())   # same count the dashboard shows
    G = json.loads((D / "climate/glaciers.json").read_text())
    gl = {g["name"]: (g["b"][0], sum(x for x in g["b"][1] if x is not None), sum(1 for x in g["b"][1] if x is not None)) for g in G["glaciers"]}
    long = [k for k, v in gl.items() if v[2] >= 40]
    A = json.loads((D / "climate/ahccd.json").read_text())
    y1 = A["t_years"][1]; up = n = 0
    for s in A["stations"]:
        if not s["t"]:
            continue
        t = {s["t"][0] + i: x for i, x in enumerate(s["t"][1]) if x is not None}
        b = [t[k] for k in range(1961, 1991) if k in t]; l = [t[k] for k in range(y1 - 9, y1 + 1) if k in t]
        if len(b) >= 25 and len(l) >= 8:
            n += 1; up += statistics.mean(l) > statistics.mean(b)
    P = json.loads((D / "cities/ct_profile.json").read_text())
    X = {f: i for i, f in enumerate(P["fields"])}
    tor = [a["v"][X["hhinc"]] for a in P["areas"].values() if a["level"] == "Census tract" and a["cma"] == "2021S0503535" and a["v"][X["hhinc"]] is not None]
    pk = gl["Peyto"]
    fy = f"{y - 1}–{str(y)[2:]}"
    big = lambda v: f"${v / 1e9:,.0f} billion"
    md = f"""# Launch copy — Canada Through Time
Generated by tools/make_launch_copy.py from the site's data files. Paste as is; don't retype numbers.
Link: {url}

## X thread (@CanadaAnalytics) — pin the first post
1/ I built a free map of Canada from official data: people, neighbourhoods, climate and where federal money goes. Every number links back to the table it came from.
{url}

2/ Ottawa spent {big(tot)} in {fy}, about ${per:,.0f} for every person in Canada. See it by department and by type, back to 2002–03.
{url}#mn=spend/{y}

3/ {up} of {n} Environment Canada weather stations with long records were warmer in {y1 - 9}–{y1} than their own 1961–1990 average. Play it from 1900.
{url}#cl=temp/{y1}

4/ Peyto Glacier has been measured every year since {pk[0]}. Running total: {('−' if pk[1] < 0 else '+')}{abs(pk[1]):.1f} m of water equivalent. {sum(1 for k in long if gl[k][1] < 0)} of the {len(long)} Canadian glaciers measured 40+ years are negative.
{url}#cl=ice/2020

5/ Every neighbourhood in 50 cities. In Toronto, median household income ranges from ${min(tor):,.0f} to ${max(tor):,.0f} across the {len(tor):,} census tracts with a published figure.
{url}#nb=535/hhinc

6/ {ncon:,} federal contracts: who won them and how. {tn:.0f}% of the value is marked non-competitive.
{url}#mn=contracts/all

7/ It's free, non-partisan, and every source is listed. Found a mistake? Reply and I'll check it against the source.

## r/dataisbeautiful — post ONE image (not the link), flair OC
Title: [OC] {up} of {n} long-running Canadian weather stations were warmer in {y1 - 9}–{y1} than their 1961–1990 average
Image: Climate → Temperature → Share → Save picture
First comment: Source: Environment and Climate Change Canada, Adjusted and Homogenized Canadian Climate Data (AHCCD). Each station is compared with its own 1961–1990 average (needs 25 of the 30 years); the 10-year average needs 8 of 10 years. Tool: my own map built with deck.gl; every number is computed from the downloaded source files. Interactive version (every year since 1900, every station's record): {url}#cl=temp/{y1}

## Hacker News
Title: Show HN: Canada Through Time – official Canadian data on one interactive map
URL: {url}
First comment: Hi HN — I built this to make Canada's open data explorable: provinces through time since 1971, all 6,000+ census tracts in 50 cities, 1,000+ homogenized weather stations, and federal spending, grants and contracts. Every raw file is fingerprinted (SHA-256) and every number is computed from it; missing values stay missing rather than becoming zero. It's static (GitHub Pages + deck.gl), sections load their data only when opened. I'd love feedback on what's confusing and what data you'd add.

## City subreddit template (one city a day; read each sub's self-promotion rules first)
Title: Every {{city}} neighbourhood mapped: income, rent, age, where people were born (2021 Census)
Body: I made a free map from Statistics Canada's 2021 Census tract data. Pick any measure or any of 47 countries of birth and see it neighbourhood by neighbourhood, compared with the other 49 cities. Grey means Statistics Canada didn't publish a value there. {url}cities/{{city-slug}}/
"""
    out = ROOT / "exports/launch/launch_copy.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md)
    print(out.relative_to(ROOT)); print(md)


if __name__ == "__main__":
    main()
